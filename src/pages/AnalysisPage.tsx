import React, { useState, useEffect } from 'react';
import { useParams, useNavigate } from 'react-router-dom';
import {
  Play,
  CheckCircle2,
  Clock,
  AlertTriangle,
  ArrowRight,
  Database,
  Cpu,
  ShieldAlert,
  RotateCcw
} from 'lucide-react';
import { runDatasetAnalysis, getDatasetById } from '../services/api';
import { AnalysisResult, Dataset } from '../types';
import { StatusBadge } from '../components/common/StatusBadge';
import { useToast } from '../context/ToastContext';
import { getDatasetWorkflowPath } from '../services/datasetNavigation';

export const AnalysisPage: React.FC = () => {
  const { id } = useParams<{ id: string }>();
  const navigate = useNavigate();
  const { success, error } = useToast();

  const [dataset, setDataset] = useState<Dataset | null>(null);
  const [isRunning, setIsRunning] = useState(false);
  const [analysisResult, setAnalysisResult] = useState<AnalysisResult | null>(null);

  const stageDefinitions = [
    { id: 1, name: 'Dataset Profiling', desc: 'Not executed by this leakage-analysis request.' },
    { id: 2, name: 'Exact Duplicate Detection', desc: 'The backend exact-duplicate detector runs for this request.' },
    { id: 3, name: 'Leakage Detection', desc: 'Optional entity, target, temporal, and contamination detectors were not requested.' },
    { id: 4, name: 'Label Analysis', desc: 'No label-anomaly detector is executed by this request.' },
    { id: 5, name: 'OOD Analysis', desc: 'Not executed by this backend analysis request.' },
    { id: 6, name: 'Distribution Analysis', desc: 'Not executed by this backend analysis request.' },
    { id: 7, name: 'Risk Assessment', desc: 'No risk score is computed by this request.' },
    { id: 8, name: 'Report Generation', desc: 'No report is generated by this request.' }
  ];

  useEffect(() => {
    async function init() {
      if (!id) return;
      const ds = await getDatasetById(id);
      setDataset(ds);
      // Auto-start analysis if not already run
      startAnalysis();
    }
    init();
  }, [id]);

  const startAnalysis = async () => {
    if (!id || isRunning) return;
    setIsRunning(true);
    setAnalysisResult(null);

    try {
      const res = await runDatasetAnalysis(id);
      setAnalysisResult(res);
      success(
        'Analysis Completed',
        'Exact duplicate detection ran. Optional detectors were not run because this request supplied no columns.'
      );
    } catch {
      error('Analysis Failed', 'Encountered an issue running integrity pipeline.');
    } finally {
      setIsRunning(false);
    }
  };

  const isCompleted = !isRunning && analysisResult !== null;
  const completedStageCount = analysisResult?.stages.filter((stage) => stage.status === 'completed').length ?? 0;

  return (
    <div className="space-y-6 max-w-4xl mx-auto animate-in fade-in duration-200">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <span className="text-xs font-mono text-teal-700 uppercase tracking-wider font-semibold">
            Pipeline Execution Node
          </span>
          <h1 className="text-2xl font-bold tracking-tight text-slate-900 font-mono mt-1">
            Automated Integrity Analysis
          </h1>
          <p className="text-xs text-slate-500 mt-1">
            Running backend-supported leakage analysis for {dataset?.name || id}.
          </p>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={startAnalysis}
            disabled={isRunning}
            className="px-3.5 py-2 text-xs font-semibold rounded-lg bg-white hover:bg-slate-50 disabled:opacity-50 text-slate-700 border border-slate-200 transition-colors flex items-center gap-1.5 shadow-2xs"
          >
            <RotateCcw className={`w-3.5 h-3.5 ${isRunning ? 'animate-spin' : ''}`} />
            <span>{isRunning ? 'Auditing...' : 'Re-Run Analysis'}</span>
          </button>

          {isCompleted && (
            <button
              onClick={() => navigate(getDatasetWorkflowPath('findings', id))}
              className="px-4 py-2 text-xs font-semibold rounded-lg bg-teal-700 hover:bg-teal-800 text-white transition-colors flex items-center gap-2 shadow-xs"
            >
              <span>View Analysis Results</span>
              <ArrowRight className="w-4 h-4" />
            </button>
          )}
        </div>
      </div>

      {/* Live Status Banner */}
      <div className={`p-5 rounded-xl border transition-all ${
        isRunning
          ? 'bg-teal-50 border-teal-200 shadow-xs'
          : isCompleted
          ? 'bg-white border-slate-200 shadow-xs'
          : 'bg-white border-slate-200 shadow-xs'
      }`}>
        <div className="flex items-center justify-between mb-3">
          <div className="flex items-center gap-2.5">
            {isRunning ? (
              <Clock className="w-5 h-5 text-teal-700 animate-spin" />
            ) : isCompleted ? (
              <CheckCircle2 className="w-5 h-5 text-emerald-600" />
            ) : (
              <Play className="w-5 h-5 text-slate-400" />
            )}
            <div>
              <p className="text-sm font-semibold text-slate-900 font-mono">
                {isRunning
                  ? 'Backend analysis request in progress'
                  : isCompleted
                  ? `Analysis Request Complete — ${analysisResult?.summary.duplicateFindings ?? 0} Exact Duplicate Findings`
                  : 'Ready to Execute Audit'}
              </p>
              <p className="text-xs text-slate-500">
                {isRunning
                  ? 'Per-detector progress is not available while the backend request runs.'
                  : isCompleted
                  ? `Exact duplicate detection ran; ${Math.max(0, stageDefinitions.length - completedStageCount)} other displayed stages were not run.`
                  : 'This request runs exact duplicate detection; optional detectors require column selections.'}
              </p>
            </div>
          </div>

          <div className="text-right">
            <span className="text-xs font-mono text-teal-700 font-bold tabular-nums">
              {isRunning
                ? 'Running'
                : isCompleted
                ? `${completedStageCount}/${stageDefinitions.length} stages`
                : `0/${stageDefinitions.length} stages`}
            </span>
          </div>
        </div>

        {/* Global Progress Bar */}
        <div className="w-full h-2 bg-slate-200 rounded-full overflow-hidden">
          <div
            className={`h-full bg-teal-600 rounded-full transition-all duration-300 ${isRunning ? 'animate-pulse' : ''}`}
            style={{
              width: isRunning
                ? '35%'
                : isCompleted
                ? `${(completedStageCount / stageDefinitions.length) * 100}%`
                : '0%'
            }}
          />
        </div>
      </div>

      {/* 8 Execution Stages Stepper */}
      <div className="bg-white border border-slate-200 rounded-xl divide-y divide-slate-100 overflow-hidden shadow-xs">
        {stageDefinitions.map((stage, idx) => {
          const isDone = isCompleted && analysisResult?.stages?.[idx]?.status === 'completed';
          const stageResult = analysisResult?.stages.find((result) => result.id === stage.id);

          return (
            <div
              key={stage.id}
              className="p-4 flex items-center justify-between gap-4 transition-colors hover:bg-slate-50/70"
            >
              <div className="flex items-center gap-3 min-w-0">
                <div
                  className={`w-7 h-7 rounded-full flex items-center justify-center text-xs font-mono font-bold shrink-0 transition-colors ${
                    isDone
                      ? 'bg-emerald-50 text-emerald-700 border border-emerald-200'
                      : 'bg-slate-100 text-slate-400 border border-slate-200'
                  }`}
                >
                  {isDone ? <CheckCircle2 className="w-4 h-4" /> : `0${stage.id}`}
                </div>

                <div className="min-w-0">
                  <p className="text-xs font-semibold truncate text-slate-900">
                    {stage.name}
                  </p>
                  <p className="text-[11px] text-slate-500 truncate">
                    {stage.desc}
                  </p>
                </div>
              </div>

              <div className="flex items-center gap-3 shrink-0">
                  {isDone && (
                    <span className="text-[11px] font-mono text-emerald-700 font-medium">
                      {stageResult?.findingsCount ?? 0} findings
                    </span>
                  )}
                {analysisResult && !isDone && (
                  <span className="text-[11px] font-mono text-slate-400">
                    Not run
                  </span>
                )}
              </div>
            </div>
          );
        })}
      </div>

      {/* Completion CTA */}
      {isCompleted && (
        <div className="p-6 bg-white border-2 border-teal-600/70 rounded-xl flex flex-col sm:flex-row sm:items-center justify-between gap-4 shadow-sm">
          <div>
            <h3 className="text-sm font-bold text-slate-900 font-mono">
              Exact Duplicate Analysis Complete
            </h3>
            <p className="text-xs text-slate-500 mt-1">
              {completedStageCount} of {stageDefinitions.length} displayed stages ran. Optional detectors were not requested.
            </p>
          </div>

          <button
            onClick={() => navigate(getDatasetWorkflowPath('findings', id))}
            className="px-5 py-2.5 text-xs font-semibold rounded-lg bg-teal-700 hover:bg-teal-800 text-white transition-colors flex items-center justify-center gap-2 shrink-0 shadow-xs"
          >
            <span>Proceed to Leakage Analysis</span>
            <ArrowRight className="w-4 h-4" />
          </button>
        </div>
      )}
    </div>
  );
};
